const list = JSON.parse(readFileSync(QPATH, 'utf8'));
let touched = 0;
const missing = [];
const errors = [];

const out = list.map(q => {
  if (q.type !== 'knowledge') return q;
  const s = SITU[q.id];
  if (!s) { missing.push(q.id); return q; }
  if (s.optionActs.length !== (q.options || []).length) {
    errors.push(`${q.id} optionActs 长度 ${s.optionActs.length} ≠ options 长度 ${q.options.length}`);
    return q;
  }
  touched++;
  // 保持字段顺序：id/type/stem/scenario/difficulty/category/analysis/enabled/options/optionActs/answer
  return {
    id: q.id,
    type: q.type,
    stem: q.stem,
    scenario: s.scenario,
    difficulty: q.difficulty,
    category: q.category,
    analysis: q.analysis,
    enabled: q.enabled,
    options: q.options,
    optionActs: s.optionActs,
    answer: q.answer
  };
});

if (errors.length) {
  console.error('注入失败：\n' + errors.join('\n'));
  process.exit(1);
}

writeFileSync(QPATH, JSON.stringify(out, null, 2) + '\n', 'utf8');

